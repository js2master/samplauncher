#!/usr/bin/env python3
"""Generate known-answer vectors for the Android omp-cef protocol client.

Two independent implementations are produced here (Python) and compared
against the C++ module (app/src/main/cpp/SAMPMOBILE/Cef) on a real device:

  * wire format  -> hand-written serializer following
                    omp-cef src/shared/packet-serializer.hpp
  * crypto       -> libsodium through PyNaCl (the exact library the PC
                    client links) + hashlib.blake2b

Writes cef_kat_vectors.h next to this script.
"""

import hashlib
import io
import struct
import zipfile
from pathlib import Path

from nacl import bindings

OUT = Path(__file__).with_name("cef_kat_vectors.h")


def ref_s(x: bytes) -> bytes:
    n = min(len(x), 4096)
    return struct.pack("<H", n) + x[:n]


def ref_b(x: bytes) -> bytes:
    return struct.pack("<I", len(x)) + x


def ref_pkt(t: int, body: bytes) -> bytes:
    return bytes([t]) + body


def ref_args(args):
    out = bytes([len(args)])
    for a in args:
        kind, val = a
        out += bytes([kind])
        if kind == 0:
            out += ref_s(val)
        elif kind == 1:
            out += struct.pack("<i", val)
        elif kind == 2:
            out += struct.pack("<f", val)
        elif kind == 3:
            out += bytes([1 if val else 0])
    return out


def main():
    vectors = []

    # 1. RequestJoin: playerid=7, version 1.3.0.0
    vectors.append(("RequestJoin",
                    ref_pkt(0, struct.pack("<iI", 7, 0x01030000))))

    # 2. HandshakeFinalize: cookie 0xAA*32, client pk 0x11*32
    vectors.append(("HandshakeFinalize",
                    ref_pkt(2, ref_b(b"\xaa" * 32) + ref_b(b"\x11" * 32))))

    # 3. JoinResponse: accepted, conv 0x11223344, manifest, versions, message
    manifest = b'{"files":[]}'
    body = (bytes([1]) + struct.pack("<I", 0x11223344) + ref_s(manifest)
            + bytes([0]) + struct.pack("<II", 0x01030000, 0x01030000)
            + ref_s(b""))
    vectors.append(("JoinResponse", ref_pkt(3, body)))

    # 4. ServerConfig: key 0x22*16, loaderUi true
    vectors.append(("ServerConfig",
                    ref_pkt(4, ref_b(b"\x22" * 16) + bytes([1]))))

    # 5. FileData: main / index.html / hash / chunk 0 of 2
    payload = b"<html></html>"
    body = (ref_s(b"main") + ref_s(b"index.html") + ref_s(b"deadbeef")
            + struct.pack("<II", 0, 2) + ref_b(payload))
    vectors.append(("FileData", ref_pkt(6, body)))

    # 6. EmitEvent CreateBrowser: id 3, url string, focused bool, chat bool
    body = (struct.pack("<i", 3) + ref_s(b"CreateBrowser")
            + ref_args([(1, 3), (0, b"http://cef/main/index.html"),
                        (3, True), (3, False)]))
    vectors.append(("EmitEvent_CreateBrowser", ref_pkt(9, body)))

    # 7. ClientEmitEvent with mixed argument types
    body = (struct.pack("<i", 5) + ref_s(b"myEvent")
            + ref_args([(1, -5), (2, 1.5), (3, True), (0, b"x")]))
    vectors.append(("ClientEmitEvent_Mixed", ref_pkt(11, body)))

    # 8. DownloadComplete quirk: default variant body == RequestJoinPacket{}
    vectors.append(("DownloadComplete",
                    ref_pkt(7, b"\xff\xff\xff\xff" + struct.pack("<I", 0))))

    # 9. RequestFiles with two entries
    body = struct.pack("<H", 2) + ref_s(b"main") + ref_s(b"index.html") \
        + ref_s(b"main") + ref_s(b"css/app.css")
    vectors.append(("RequestFiles", ref_pkt(5, body)))

    # ---- crypto vectors (libsodium semantics) ----
    client_sk = bytes(range(32))
    server_sk = bytes(range(32, 64))
    client_pk = bindings.crypto_scalarmult_base(client_sk)
    server_pk = bindings.crypto_scalarmult_base(server_sk)
    q = bindings.crypto_scalarmult(client_sk, server_pk)
    keys = hashlib.blake2b(q + client_pk + server_pk, digest_size=64).digest()
    rx, tx = keys[:32], keys[32:]

    msg = b"hello omp-cef"
    nonce = bytes(range(24))
    box_key = bytes(range(0x40, 0x60))
    ct = bindings.crypto_secretbox(msg, nonce, box_key)

    hdr = f"""// Generated by tests/cef/gen_vectors.py - do not edit.
#pragma once

struct CefKatVector {{ const char* name; const char* hex; }};

static const CefKatVector kCefKatVectors[] = {{
"""
    for name, data in vectors:
        hdr += f'    {{ "{name}", "{data.hex()}" }},\n'
    hdr += "};\n"
    hdr += f'static const short kCefKatVectorCount = {len(vectors)};\n\n'

    hdr += f'static const char* kClientSk = "{client_sk.hex()}";\n'
    hdr += f'static const char* kClientPk = "{client_pk.hex()}";\n'
    hdr += f'static const char* kServerSk = "{server_sk.hex()}";\n'
    hdr += f'static const char* kServerPk = "{server_pk.hex()}";\n'
    hdr += f'static const char* kSharedQ = "{q.hex()}";\n'
    hdr += f'static const char* kSessionRx = "{rx.hex()}";\n'
    hdr += f'static const char* kSessionTx = "{tx.hex()}";\n'
    hdr += f'static const char* kBoxKey = "{box_key.hex()}";\n'
    hdr += f'static const char* kBoxNonce = "{nonce.hex()}";\n'
    hdr += f'static const char* kBoxMsg = "{msg.hex()}";\n'
    hdr += f'static const char* kBoxCt = "{ct.hex()}";\n'

    # ---- resource pak vectors (stage 5: zip parsing + OCEF2 entry decode) ----
    def ocef_plain(payload: bytes) -> bytes:
        return b"OCEF2" + bytes([0]) + payload

    html = b"<!doctype html><title>pak</title>"
    script = b"console.log('from pak');"
    stored = b"stored entry (zip method 0)"

    pak_buf = io.BytesIO()
    with zipfile.ZipFile(pak_buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        archive.writestr("index.html", ocef_plain(html))
        archive.writestr("stored.txt", ocef_plain(stored), compress_type=zipfile.ZIP_STORED)
        archive.writestr("sub/app.js", ocef_plain(script))
    pak_bytes = pak_buf.getvalue()

    evil_buf = io.BytesIO()
    with zipfile.ZipFile(evil_buf, "w") as archive:
        archive.writestr("../evil.html", ocef_plain(b"pwn"))
    evil_bytes = evil_buf.getvalue()

    hdr += f'static const char* kCefPak = "{pak_bytes.hex()}";\n'
    hdr += f'static const char* kCefPakEvil = "{evil_bytes.hex()}";\n'
    hdr += f'static const char* kCefPakHtml = "{html.hex()}";\n'
    hdr += f'static const char* kCefPakStored = "{stored.hex()}";\n'
    hdr += f'static const char* kCefPakScript = "{script.hex()}";\n'

    OUT.write_text(hdr, encoding="utf-8")
    print(f"wrote {OUT} ({len(vectors)} packet vectors)")


if __name__ == "__main__":
    main()
